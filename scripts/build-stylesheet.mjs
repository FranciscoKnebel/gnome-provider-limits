import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const defaultRoot = join(dirname(fileURLToPath(import.meta.url)), "..");

// base.css goes last: its usage thresholds must still win the cascade, exactly
// as the trailing threshold blocks did in the original combined stylesheet.
const sources = [
  "src/styles/cards.css",
  "src/styles/cockpit.css",
  "src/styles/compact.css",
  "src/styles/base.css",
];

function normalize(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");
}

/** Single source of truth for the generated stylesheet, shared with its test. */
export function buildStylesheet(root = defaultRoot) {
  const body = sources
    .map((relative) => normalize(readFileSync(join(root, relative), "utf8")))
    .join("\n");

  const header = [
    "/* Generated by scripts/build-stylesheet.mjs from src/styles/*.css.",
    "   Do not edit by hand. Run npm run build:stylesheet instead. */",
    "",
  ].join("\n");

  return `${header}${body}\n`;
}

const invokedAsScript =
  process.argv[1] !== undefined &&
  resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url));

if (invokedAsScript) {
  writeFileSync(join(defaultRoot, "src/stylesheet.css"), buildStylesheet());
}
