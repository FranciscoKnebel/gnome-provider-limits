import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";

import { assert } from "../helpers/node-harness.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "../..");
const sources = [
  "src/styles/cards.css",
  "src/styles/cockpit.css",
  "src/styles/compact.css",
  "src/styles/base.css",
];

function normalize(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .split("\n")
    .map((line) => line.trimEnd())
    .filter((line) => line.trim() !== "")
    .join("\n");
}

test("the committed stylesheet matches the generated sources", () => {
  const header = [
    "/* Generated by scripts/build-stylesheet.mjs from src/styles/*.css.",
    "   Do not edit by hand. Run npm run build:stylesheet instead. */",
    "",
  ].join("\n");
  const expected = `${header}${sources.map((path) => normalize(readFileSync(join(root, path), "utf8"))).join("\n")}\n`;
  const committed = readFileSync(join(root, "src/stylesheet.css"), "utf8");

  assert.equal(committed, expected, "run npm run build:stylesheet and commit the result");
});
